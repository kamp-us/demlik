import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { describe, expect, it } from "vitest";
import { packs } from "../doc-links";
import { rules } from "./rules";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const AGENTS = join(ROOT, "AGENTS.md");
const WRITE = process.env.TEA_DOCS_WRITE === "1";
const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8"));

async function readDocs(dir = "docs"): Promise<Map<string, string>> {
  const pages = new Map<string, string>();
  for (const entry of (
    await readdir(join(ROOT, dir), { withFileTypes: true })
  ).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
    const path = posix.join(dir, entry.name);
    if (entry.isDirectory()) {
      for (const [file, text] of await readDocs(path)) pages.set(file, text);
    } else if (entry.name.endsWith(".md")) {
      pages.set(path, await readFile(join(ROOT, path), "utf8"));
    }
  }
  return pages;
}

const docs = await readDocs();
const h1 = (text: string) => text.match(/^# (.+)$/m)?.[1];

function renderIndex(): string {
  const dirs = new Map<string, string[]>();
  for (const [path, text] of docs) {
    const dir = posix.dirname(path);
    const title = dir.startsWith("docs/reference")
      ? ""
      : ` ${JSON.stringify(h1(text))}`;
    const files = dirs.get(dir) ?? [];
    files.push(`${posix.basename(path)}${title}`);
    dirs.set(dir, files);
  }
  return [...dirs]
    .sort(([a], [b]) => a.localeCompare(b, "en"))
    .map(([dir, files]) => `|${dir}:{${files.join(",")}}`)
    .join("\n");
}

function renderAgents(): string {
  return [
    "# @demlik/tea for coding agents",
    "",
    `Version: ${pkg.version}`,
    "Use the docs and types shipped in this package: `node_modules/@demlik/tea/docs/` and `node_modules/@demlik/tea/dist/**/*.d.ts`.",
    "The API changed between versions. Prefer these files over memory, external documentation and other copies of tea.",
    "IMPORTANT: Prefer retrieval-led reasoning over pre-training-led reasoning. Read the relevant page before writing code.",
    "",
    "<!-- Generated by pnpm --filter @demlik/tea run docs:agents. Do not edit. -->",
    "",
    "## Before you hand-write it",
    "",
    "| When | Use | From | Page |",
    "| --- | --- | --- | --- |",
    ...rules.map((r) => {
      const use = r.use
        .split(", ")
        .map((name) => `\`${name}\``)
        .join(", ");
      const instead = r.instead ? `. Replaces ${r.instead}` : "";
      return `| ${r.when} | ${use}${instead} | \`${r.from}\` | [Read](${r.page}) |`;
    }),
    "",
    "## Docs index",
    "",
    "Paths are relative to this package. Reference pages list exports and signatures.",
    "",
    "```text",
    renderIndex(),
    "```",
    "",
  ].join("\n");
}

// Include explicit reference ids and Markdown heading slugs, outside code fences.
function anchors(text: string): Set<string> {
  const prose = text.replace(/^```[^\n]*\n[\s\S]*?^```/gm, "");
  const ids = new Set(
    [...prose.matchAll(/<a id="([^"]+)"><\/a>/g)].map((m) => m[1] ?? ""),
  );
  const counts = new Map<string, number>();
  for (const [, heading = ""] of prose.matchAll(/^#{1,6} (.+)$/gm)) {
    const slug = heading
      .toLowerCase()
      .replace(/[^\p{L}\p{N}_\- ]/gu, "")
      .replace(/ /g, "-");
    const count = counts.get(slug) ?? 0;
    ids.add(count === 0 ? slug : `${slug}-${count}`);
    counts.set(slug, count + 1);
  }
  return ids;
}

const drift = (actual: string) =>
  actual === renderAgents() ? [] : ["AGENTS.md"];

describe("coding agent guide", () => {
  describe.runIf(WRITE)("regenerate (TEA_DOCS_WRITE=1)", () => {
    it("writes AGENTS.md", async () => {
      await writeFile(AGENTS, renderAgents(), "utf8");
    });
  });

  describe.skipIf(WRITE)("proofs", () => {
    it("every use resolves through the export map and its source entry's exports", () => {
      const entries = new Map<string, string>();
      for (const rule of rules) {
        const subpath =
          rule.from === pkg.name ? "." : `.${rule.from.slice(pkg.name.length)}`;
        const entry = pkg.exports[subpath]?.types;
        expect(entry, rule.from).toMatch(/^\.\/dist\/.+\.d\.ts$/);
        entries.set(
          rule.from,
          join(
            ROOT,
            entry.replace("./dist/", "src/").replace(/\.d\.ts$/, ".ts"),
          ),
        );
      }
      const config = ts.readConfigFile(
        join(ROOT, "tsconfig.json"),
        ts.sys.readFile,
      );
      const { options } = ts.parseJsonConfigFileContent(
        config.config,
        ts.sys,
        ROOT,
      );
      const program = ts.createProgram([...entries.values()], options);
      const checker = program.getTypeChecker();
      for (const rule of rules) {
        const source = program.getSourceFile(entries.get(rule.from) ?? "");
        const module = source && checker.getSymbolAtLocation(source);
        if (!module) throw new Error(`No source module for ${rule.from}`);
        const exported = checker.getExportsOfModule(module);
        for (const use of rule.use.split(", ")) {
          const [name = "", ...members] = use.split(".");
          const symbol = exported.find((symbol) => symbol.name === name);
          if (!symbol || !source)
            throw new Error(`${rule.from} does not export ${name}`);
          let type = checker.getTypeOfSymbolAtLocation(symbol, source);
          for (const member of members) {
            const property = type.getProperty(member);
            if (!property)
              throw new Error(`${rule.from} does not export ${use}`);
            type = checker.getTypeOfSymbolAtLocation(property, source);
          }
        }
      }
    });

    it("every rule page and anchor exists in the shipped docs", () => {
      for (const rule of rules) {
        const [page = "", anchor] = rule.page.split("#");
        const text = docs.get(page);
        expect(text, rule.page).toBeDefined();
        expect(packs(pkg.files, page), rule.page).toBe(true);
        if (anchor)
          expect(anchors(text ?? "").has(anchor), rule.page).toBe(true);
      }
    });

    it("the index includes every docs page once, with H1 titles outside reference", () => {
      const indexed = renderIndex()
        .split("\n")
        .flatMap((line) => {
          const [, dir = "", files = ""] =
            line.match(/^\|([^:]+):\{(.*)\}$/) ?? [];
          return [
            ...files.matchAll(
              /(?:^|,)([^,]+?\.md)(?: "(?:[^"\\]|\\.)*")?(?=,|$)/g,
            ),
          ].map((m) => `${dir}/${m[1]}`);
        });
      expect(indexed.sort()).toEqual([...docs.keys()].sort());
      for (const [page, text] of docs) {
        if (!page.startsWith("docs/reference/")) {
          expect(h1(text), page).toBeDefined();
          expect(renderIndex()).toContain(
            `${posix.basename(page)} ${JSON.stringify(h1(text))}`,
          );
        }
      }
    });

    it("the complete guide stays below 12KB", () => {
      expect(Buffer.byteLength(renderAgents(), "utf8")).toBeLessThan(12_000);
    });

    it("the committed AGENTS.md is what the generator writes", async () => {
      // The package's own test run is the gate: a stale guide fails here, in CI's tea job.
      expect(drift(await readFile(AGENTS, "utf8"))).toEqual([]);
    });

    it("a tampered AGENTS.md is reported as drift", async () => {
      expect(
        drift(`${await readFile(AGENTS, "utf8")}\n<!-- tampered -->`),
      ).toEqual(["AGENTS.md"]);
      expect(drift(renderAgents())).toEqual([]);
    });
  });
});
